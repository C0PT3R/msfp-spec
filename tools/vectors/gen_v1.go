type v1Exchange struct {
	Name              string `json:"name"`
	Signer            string `json:"signer"`
	Answerer          string `json:"answerer"`
	Method            string `json:"method"`
	Host              string `json:"host"`
	Target            string `json:"target"`
	Date              string `json:"date"`
	Nonce             string `json:"nonce"`
	NonceText         string `json:"nonceText"`
	Body              string `json:"body"`
	Message           string `json:"message"`
	Signature         string `json:"signature"`
	Status            int    `json:"status"`
	AnswerContentType string `json:"answerContentType"`
	AnswerBody        string `json:"answerBody"`
	AnswerMessage     string `json:"answerMessage"`
	AnswerSignature   string `json:"answerSignature"`
}

func v1Exch(name, signer, answerer, host, target, date string, nonce []byte, body string, status int, ct, answerBody string) v1Exchange {
	s, a := testKeys[signer], testKeys[answerer]
	nt := b64.EncodeToString(nonce)
	msg := core1.requestMessage("POST", host, target, date, nt, body)
	am := core1.answerMessage(nt, status, ct, answerBody)
	return v1Exchange{name, signer, answerer, "POST", host, target, date, hex.EncodeToString(nonce), nt,
		body, msg, s.sign(msg), status, ct, answerBody, am, a.sign(am)}
}

type v1ExchangesFile struct {
	About     []string     `json:"about"`
	Exchanges []v1Exchange `json:"exchanges"`
}

const (
	ctJSON    = "application/json"
	ctProblem = "application/problem+json"
	hostA     = "a.example.org"
	hostB     = "192.0.2.10:8096"
	fed       = "/api/v1/federation/"
)

func v1PairBody() string {
	secret := mustHex(secretS)
	return fmt.Sprintf(`{"address":%q,"name":"Server B","secretHash":%q,"proof":%q,"nextCommitment":%q}`,
		addrB1, b64.EncodeToString(sha(secret)), core1.proof(secret, keyB.pub, addrB1), commitment(keyB2.pub))
}

func v1HelloBody() string {
	return fmt.Sprintf(`{"state":"paired","core":[0,1],"parts":{"catalog":[1],"playback":[1],"media":[1]},"certificates":[%q],"address":%q}`,
		pin(certA), addrA)
}

func genV1Exchanges() []byte {
	pairAnswer := fmt.Sprintf(`{"name":"Server A","nextCommitment":%q}`, commitment(keyA2.pub))
	helloAnswer := fmt.Sprintf(`{"state":"paired","core":[1],"parts":{"catalog":[1]},"certificates":[%q]}`, pin(certB))
	notSupported := `{"type":"not-supported","title":"Not supported","status":404}` + "\n"
	return encode(v1ExchangesFile{
		About: []string{
			"Signed requests and answers of MSFP core version 1 (spec/v1/core.md section 17), under the MSFP labels and headers. Generated by tools/vectors; no implementation has produced them yet.",
			"Header names: MSFP-Key (the signer's public key), MSFP-Date (date), MSFP-Nonce (nonceText), MSFP-Signature (signature); the answer carries MSFP-Signature (answerSignature) and Content-Type (answerContentType).",
			"nonce: the 16 nonce bytes, hex. body and answerBody: the exact bytes, as JSON strings. message and answerMessage: the signed bytes, lines joined by a line feed, no final one.",
		},
		Exchanges: []v1Exchange{
			v1Exch("pair", "b", "a", hostA, fed+"pair", "1800000000", seq(0x60, 16), v1PairBody(), 200, ctJSON, pairAnswer),
			v1Exch("hello", "a", "b", hostB, fed+"hello", "1800000060", seq(0x70, 16), v1HelloBody(), 200, ctJSON, helloAnswer),
			v1Exch("refused hello", "a", "b", hostB, fed+"hello", "1800000120", seq(0x80, 16), v1HelloBody(), 404, ctProblem, notFound),
			v1Exch("play, to a peer without playback", "a", "b", hostB, fed+"play", "1800000180", seq(0x90, 16), `{"title":"movie/tmdb/949"}`, 404, ctProblem, notSupported),
		},
	})
}

// rotationStatement is core.md section 12.2's statement.
func rotationStatement(old, nu []byte, next string, date int64) string {
	if next == "" {
		next = "-"
	}
	return "msfp-key-rotation-1\n" + b64.EncodeToString(old) + "\n" + b64.EncodeToString(nu) + "\n" + next + "\n" + strconv.FormatInt(date, 10)
}

func revocationStatement(k []byte, date int64) string {
	return "msfp-key-revocation-1\n" + b64.EncodeToString(k) + "\n" + strconv.FormatInt(date, 10)
}

type rotation struct {
	From           string `json:"from"`
	To             string `json:"to"`
	Next           string `json:"next"`
	OldKey         string `json:"oldKey"`
	NewKey         string `json:"newKey"`
	NextCommitment string `json:"nextCommitment"`
	Date           int64  `json:"date"`
	Statement      string `json:"statement"`
	OldSignature   string `json:"oldSignature"`
	NewSignature   string `json:"newSignature"`
}

type rotationFile struct {
	About    []string   `json:"about"`
	Rotation rotation   `json:"rotation"`
	Exchange v1Exchange `json:"exchange"`
}

func genV1Rotation() []byte {
	const date = 1800100000
	st := rotationStatement(keyA.pub, keyA2.pub, commitment(keyA3.pub), date)
	r := rotation{"a", "a2", "a3", keyA.text(), keyA2.text(), commitment(keyA3.pub), date, st, keyA.sign(st), keyA2.sign(st)}
	body := fmt.Sprintf(`{"newKey":%q,"nextCommitment":%q,"date":%d,"oldSignature":%q,"newSignature":%q}`,
		r.NewKey, r.NextCommitment, date, r.OldSignature, r.NewSignature)
	return encode(rotationFile{
		About: []string{
			"Server A rotates from key a to key a2, committing to a3 as the key after a2 (spec/v1/core.md section 12). Generated by tools/vectors; no implementation has produced them yet.",
			"The statement is signed with the old key (oldSignature) and the new one (newSignature). The rotate request is signed with the old key, a; server B answers that a2 is now current.",
			"Server B holds the commitment to a2 (keys.json, a2's commitment, sent in A's pair answer), so the rotation takes effect at once.",
		},
		Rotation: r,
		Exchange: v1Exch("rotate", "a", "b", hostB, fed+"rotate", strconv.Itoa(date), seq(0xa0, 16), body, 200, ctJSON, `{"state":"rotated"}`),
	})
}

type revocation struct {
	Key       string `json:"key"`
	Public    string `json:"public"`
	Date      int64  `json:"date"`
	Statement string `json:"statement"`
	Signature string `json:"signature"`
}

type revocationFile struct {
	About      []string   `json:"about"`
	Revocation revocation `json:"revocation"`
	Exchange   v1Exchange `json:"exchange"`
}

func genV1Revocation() []byte {
	const date = 1800200000
	st := revocationStatement(keyA.pub, date)
	r := revocation{"a", keyA.text(), date, st, keyA.sign(st)}
	body := fmt.Sprintf(`{"date":%d,"signature":%q}`, date, r.Signature)
	return encode(revocationFile{
		About: []string{
			"Server A revokes key a (spec/v1/core.md section 12.6), signed with that key. Generated by tools/vectors; no implementation has produced them yet.",
			"This case stands apart from rotation.json: here a is still A's current key.",
		},
		Revocation: r,
		Exchange:   v1Exch("revoke", "a", "b", hostB, fed+"revoke", strconv.Itoa(date), seq(0xb0, 16), body, 200, ctJSON, `{"state":"suspended"}`),
	})
}

type v1StrictFile struct {
	About     []string  `json:"about"`
	Addresses []verdict `json:"addresses"`
	Codes     []verdict `json:"codes"`
	Names     []verdict `json:"mediaNames"`
	Bases     []verdict `json:"bases"`
	Dests     []verdict `json:"destinations"`
}

// nameVerdicts are media file and track names (spec/v1/media.md section 1).
func nameVerdicts() []verdict {
	var out []verdict
	for _, n := range []string{"master.m3u8", "s0.mp4", "file", "s3", "a.b-c_d", "...", ".hidden",
		".", "..", "", "a/b", "a%2Fb", "a b", "é", strings.Repeat("a", 64), strings.Repeat("a", 65)} {
		ok, r := reason(checkMediaName(n))
		out = append(out, verdict{Text: n, Valid: ok, Reason: r})
	}
	return out
}

// baseVerdicts are discovery documents' base paths (spec/v1/core.md).
func baseVerdicts() []verdict {
	var out []verdict
	for _, b := range []string{"/api/v1/federation/", "/srv/media/api/v1/federation/", "/a.b/~c/api/v1/federation/",
		"/srv/../api/v1/federation/", "/./api/v1/federation/", "/srv/./media/api/v1/federation/", "/srv//api/v1/federation/",
		"/srv%2Fmedia/api/v1/federation/", "/srv%2e%2e/api/v1/federation/", "srv/api/v1/federation/", "/api/v1/federation",
		"/api/v2/federation/", "/" + strings.Repeat("a", 240) + "/api/v1/federation/"} {
		ok, r := reason(checkBase(b))
		out = append(out, verdict{Text: b, Valid: ok, Reason: r})
	}
	return out
}

func genV1Strict() []byte {
	return encode(v1StrictFile{
		About: []string{
			"Addresses and pairing codes under core version 1's rules (spec/v1/core.md sections 2 and 5): https only, prefix msfp-pair-1. Every other case of vectors/v0-strict.json holds for core 1 unchanged. Generated by tools/vectors.",
			"mediaNames: file and track names in media URLs (spec/v1/media.md section 1). bases: the discovery document's base (spec/v1/core.md, the discovery document).",
			"destinations: IP addresses a server connects to for a peer by default (valid), or refuses (spec/v1/core.md section 3.3; also version 0's section 3.2).",
		},
		Addresses: addressVerdicts(false),
		Codes:     codeVerdicts(core1, false),
		Names:     nameVerdicts(),
		Bases:     baseVerdicts(),
		Dests:     destinationVerdicts(),
	})
}
